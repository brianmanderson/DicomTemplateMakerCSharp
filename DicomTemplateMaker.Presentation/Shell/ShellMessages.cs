        /// <summary>The one-line summary in the problems panel; empty when there are none.</summary>
        public static string ProblemsLine(IReadOnlyList<TemplateProblem> problems)
        {
            ArgumentNullException.ThrowIfNull(problems);
            if (problems.Count == 0)
            {
                return string.Empty;
            }

            var parts = new List<string>();
            if (problems.Any(p => p.Kind == TemplateProblemKind.LibraryUnreadable))
            {
                parts.Add("the ontology library cannot be read, so no template is listed");
            }

            if (problems.Any(p => p.Kind == TemplateProblemKind.FolderUnreadable))
            {
                parts.Add("the template folder cannot be read");
            }

            int unreadable = problems.Where(p => p.Kind == TemplateProblemKind.TemplateUnreadable).Select(p => p.Subject).Distinct().Count();
            if (unreadable > 0)
            {
                parts.Add(Text.Count(unreadable, "template") + " cannot be read and " + (unreadable == 1 ? "is" : "are") + " not listed");
            }

            int legacy = problems.Where(p => p.Kind == TemplateProblemKind.LegacyFilesKept).Select(p => p.Subject).Distinct().Count();
            if (legacy > 0)
            {
                parts.Add(Text.Count(legacy, "template") + (legacy == 1 ? " has" : " have") + " legacy files that were kept");
            }

            if (problems.Any(p => p.Kind == TemplateProblemKind.LibraryNotUpdated))
            {
                parts.Add("the ontology library could not be updated");
            }

            string line = string.Join("; ", parts);
            return "⚠ " + char.ToUpperInvariant(line[0]) + line.Substring(1) + ".";
        }

        /// <summary>Every problem, for the Details button and the problems tooltip.</summary>
