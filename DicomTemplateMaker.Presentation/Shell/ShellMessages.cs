                + Paragraph + "The program tries to continue. If it behaves oddly, close it and start it again.";
        }

        private static string WhyNoTestRt(RunReport report)
        {
            if (report.Errors.Count > 0)
            {
                return string.Join(" ", report.Errors.Select(e => e.Message));
            }

            if (report.Count(SkipReason.AlreadyDone) > 0)
            {
                return "a test RT for the sample CT is already in the folder.";
            }

            if (report.Count(SkipReason.NoMatch) > 0)
            {
                return "the sample CT does not meet the template's DICOM requirements (Series or Study Description).";
            }

            SkippedItem? skipped = report.Skipped.FirstOrDefault();
            return skipped != null ? skipped.Reason + ": " + skipped.Detail : "no image series was found.";
        }
