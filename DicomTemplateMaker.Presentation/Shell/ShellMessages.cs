        /// <summary>The result of "Create folder with loadable RTs": RTs written and every template that got none, with why.</summary>
        public static string DescribeTestRts(TestRtResult result)
        {
            ArgumentNullException.ThrowIfNull(result);
            var text = new StringBuilder();
            if (result.Errors.Count > 0)
            {
                text.Append("No test RTs were written.").Append(Paragraph).Append(Text.List(result.Errors));
                return text.ToString();
            }

            text.Append("Wrote ").Append(Text.Count(result.WrittenCount, "test RT")).Append(" into ").Append(result.OutputFolder).Append('.');
            var notWritten = new List<string>();
            var roiLines = new List<string>();
            foreach ((string template, RunReport report) in result.Reports)
            {
                if (report.WrittenCount == 0)
                {
                    notWritten.Add(template + ": " + WhyNoTestRt(report));
                }

                roiLines.AddRange(report.RoiFailures.Select(f => $"{template}: ROI '{f.RoiName}' left out: {f.Reason}"));
            }

            if (notWritten.Count > 0)
            {
                text.Append(Paragraph).Append(Text.Count(notWritten.Count, "template")).Append(" wrote no RT:").AppendLine().Append(Text.List(notWritten));
            }

            if (roiLines.Count > 0)
            {
                text.Append(Paragraph).Append("ROIs left out of the written RTs:").AppendLine().Append(Text.List(roiLines));
            }

            return text.ToString();
        }

