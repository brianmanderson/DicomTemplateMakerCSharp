        /// <summary>The result of a Varian XML export.</summary>
        public static string DescribeExport(VarianExportResult result)
        {
            ArgumentNullException.ThrowIfNull(result);
            var text = new StringBuilder();
            text.Append("Wrote ").Append(Text.Count(result.Written.Count, "Varian XML file")).Append(" to ").Append(result.OutputFolder).Append('.');
            if (result.SkippedExisting.Count > 0)
            {
                text.Append(Paragraph).Append("Kept ").Append(Text.Count(result.SkippedExisting.Count, "existing file")).Append(" unchanged: ")
                    .Append(string.Join(", ", result.SkippedExisting.Take(20))).Append(result.SkippedExisting.Count > 20 ? ", …" : string.Empty).Append('.');
            }

            if (result.Failed.Count > 0)
            {
                text.Append(Paragraph).Append(Text.Count(result.Failed.Count, "template")).Append(result.Failed.Count == 1 ? " was" : " were").Append(" not exported:").AppendLine()
                    .Append(Text.List(result.Failed.Select(f => f.Template + ": " + f.Reason)));
            }

            List<string> skipped = result.Written
                .SelectMany(r => r.SkippedStructures.Select(s => $"{Path.GetFileName(r.Source)}: ROI '{s.Structure}' left out: {s.SkipReason}"))
                .ToList();
            if (skipped.Count > 0)
            {
                text.Append(Paragraph).Append("ROIs left out of the written files:").AppendLine().Append(Text.List(skipped));
            }

            return text.ToString();
        }

        /// <summary>Asks before an import replaces existing templates.</summary>
        public static string ConfirmImportReplace(string templateRoot, IReadOnlyList<string> existingTemplates, int importable)
        {
            ArgumentNullException.ThrowIfNull(existingTemplates);
            var text = new StringBuilder();
            text.Append(existingTemplates.Count == 1 ? "This template already exists in " : $"These {existingTemplates.Count} templates already exist in ")
                .Append(templateRoot).Append(':').AppendLine().AppendLine(Text.List(existingTemplates, 20)).AppendLine();
            text.Append("Importing replaces ").Append(existingTemplates.Count == 1 ? "its" : "their").Append(" ROIs with the ones in the XML file")
                .Append(existingTemplates.Count == 1 ? "" : "s").Append("; monitored folders and DICOM requirements are kept.").Append(Paragraph);
            int others = importable - existingTemplates.Count;
            text.Append("Yes: replace ").Append(existingTemplates.Count == 1 ? "it" : "them").Append(" and import the other ").Append(others).Append('.').AppendLine()
                .Append("No: keep ").Append(existingTemplates.Count == 1 ? "it" : "them").Append(" unchanged and import only the other ").Append(others).Append('.').AppendLine()
                .Append("Cancel: import nothing.");
            return text.ToString();
        }

        /// <summary>The result of a Varian XML import: imported templates, failed files and skipped structures.</summary>
        public static string DescribeImport(VarianImportResult result)
        {
            ArgumentNullException.ThrowIfNull(result);
            List<VarianXmlReport> imported = result.Imported.ToList();
            var text = new StringBuilder();
            text.Append("Imported ").Append(Text.Count(imported.Count, "template")).Append(" into ").Append(result.TemplateRoot);
            text.Append(imported.Count == 0 ? "." : ":" + Environment.NewLine + Text.List(imported.Select(r => Path.GetFileName(r.Target ?? r.Source) + $" ({Text.Count(r.SucceededCount, "ROI")})"), 20));
            if (result.SkippedExisting.Count > 0)
            {
                text.Append(Paragraph).Append("Kept ").Append(Text.Count(result.SkippedExisting.Count, "existing template")).Append(" unchanged: ")
                    .Append(string.Join(", ", result.SkippedExisting.Take(20))).Append(result.SkippedExisting.Count > 20 ? ", …" : string.Empty).Append('.');
            }

            List<string> failed = result.FailedReports.Select(r => Path.GetFileName(r.Source) + ": " + r.Error)
                .Concat(result.NotImported.Select(n => Path.GetFileName(n.File) + ": " + n.Reason))
                .ToList();
            if (failed.Count > 0)
            {
                text.Append(Paragraph).Append(Text.Count(failed.Count, "file")).Append(failed.Count == 1 ? " was" : " were").Append(" not imported:").AppendLine().Append(Text.List(failed));
            }

            List<string> skipped = imported
                .SelectMany(r => r.SkippedStructures.Select(s => $"{Path.GetFileName(r.Target ?? r.Source)}: structure '{s.Structure}' left out: {s.SkipReason}"))
                .ToList();
            if (skipped.Count > 0)
            {
                text.Append(Paragraph).Append("Structures left out of the imported templates:").AppendLine().Append(Text.List(skipped));
            }

            return text.ToString();
        }

