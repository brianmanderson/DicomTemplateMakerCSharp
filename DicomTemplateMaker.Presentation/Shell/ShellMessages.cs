        private static readonly string Paragraph = Environment.NewLine + Environment.NewLine;

        /// <summary>Asked when a bulk action finds no selected template: act on all of them instead?</summary>
        public static string UseAllTemplates(string action, int total, int hiddenSelected)
        {
            var text = new StringBuilder("No templates are selected");
            text.Append(hiddenSelected > 0 ? $" among the templates shown ({Text.Count(hiddenSelected, "selected template")} {Text.IsAre(hiddenSelected)} hidden by the search)." : ".");
            text.Append(Paragraph).Append(action).Append(" all ").Append(Text.Count(total, "template")).Append('?');
            return text.ToString();
        }

        /// <summary>The sentence about selected templates hidden by the search, which bulk actions leave out; empty when there are none.</summary>
        public static string HiddenNote(int hiddenSelected)
        {
            return hiddenSelected == 0
                ? string.Empty
                : $"{Text.Count(hiddenSelected, "selected template")} hidden by the current search {Text.IsAre(hiddenSelected)} left out. Clear the search to include {(hiddenSelected == 1 ? "it" : "them")}.";
        }

        /// <summary>Confirms "Delete previously generated RTs", naming the templates and the folders that will be searched.</summary>
        public static string ConfirmDeleteGenerated(IReadOnlyList<MonitoredTemplate> templates, int hiddenSelected, RunnerState runnerState)
        {
            ArgumentNullException.ThrowIfNull(templates);
            List<MonitoredTemplate> withPaths = templates.Where(t => t.Paths.Count > 0).ToList();
            List<string> withoutPaths = templates.Where(t => t.Paths.Count == 0).Select(t => t.Name).ToList();
            var text = new StringBuilder();
            text.Append("Delete the RTs generated by ").Append(Text.Count(withPaths.Count, "template")).Append('?').Append(Paragraph);
            text.AppendLine("These folders, and all folders inside them, will be searched:");
            var lines = new List<string>();
            foreach (MonitoredTemplate template in withPaths)
            {
                lines.Add(template.Name + ": " + string.Join("; ", template.Paths));
            }

            text.AppendLine(Text.List(lines, 12));
            text.AppendLine();
            text.Append("Only files named <template>_UID<series UID>.dcm written by these templates are deleted. They are deleted permanently, "
                + "not moved to the Recycle Bin; other files are not touched.");
            if (withoutPaths.Count > 0)
            {
                text.Append(Paragraph).Append(Text.Count(withoutPaths.Count, "selected template")).Append(" without monitored folders ")
                    .Append(withoutPaths.Count == 1 ? "has" : "have").Append(" nothing to delete: ").Append(string.Join(", ", withoutPaths.Take(10)))
                    .Append(withoutPaths.Count > 10 ? ", …" : string.Empty).Append('.');
            }

            if (hiddenSelected > 0)
            {
                text.Append(Paragraph).Append(HiddenNote(hiddenSelected));
            }

            // A running generator writes an RT for every matching series that has none, so it would write the deleted
            // ones again within one scan: it is stopped for the delete and left stopped.
            text.Append(Paragraph);
            if (runnerState != RunnerState.Stopped)
            {
                text.Append("The RT generator is stopped before deleting and stays stopped afterwards. ");
            }

            text.Append("Whenever the RT generator runs, it writes a new RT, with the template as it is then, for every matching series in these folders "
                + "that has none, so the deleted RTs come back within seconds of starting it. To keep them deleted, first remove these folders from the "
                + "templates' monitored folders or change their DICOM requirements. An RT generator running elsewhere on these folders (the command-line "
                + "tool, or this program on another computer) writes them again straight away.");
            return text.ToString();
        }

        /// <summary>The result of deleting generated RTs: the count deleted and every failure.</summary>
        /// <param name="report">What was deleted.</param>
        /// <param name="generatorStopped">True when the RT generator was running and was stopped for the delete.</param>
        public static string DescribeDeleteGenerated(DeleteReport report, bool generatorStopped = false)
        {
            ArgumentNullException.ThrowIfNull(report);
            var text = new StringBuilder();
            text.Append("Deleted ").Append(Text.Count(report.Deleted.Count, "generated RT")).Append('.');
            if (report.Failed.Count > 0)
            {
                text.Append(Paragraph).Append(Text.Count(report.Failed.Count, "file")).Append(" could not be deleted:").AppendLine()
                    .Append(Text.List(report.Failed.Select(f => f.Path + ": " + f.Message)));
            }

            if (report.Errors.Count > 0)
            {
                text.Append(Paragraph).Append("These could not be searched:").AppendLine()
                    .Append(Text.List(report.Errors.Select(e => e.Context + ": " + e.Message)));
            }

            if (report.HasFailures)
            {
                text.Append(Paragraph).Append("The details are in the log.");
            }

            if (generatorStopped)
            {
                text.Append(Paragraph).Append("The RT generator is stopped. When you start it again, it writes RTs again for the matching series that have none, "
                    + "using the templates as they are then.");
            }

            return text.ToString();
        }

        /// <summary>
        /// Confirms moving template folders to the Recycle Bin. <paramref name="notRecyclable"/> are the selected folders
        /// that have no Recycle Bin (see <see cref="RecycleBinRule"/>): they are named as not deleted.
        /// </summary>
        public static string ConfirmDeleteTemplates(IReadOnlyList<(string Name, string Folder)> templates, int hiddenSelected, IReadOnlyList<NotRecyclable>? notRecyclable = null)
        {
            ArgumentNullException.ThrowIfNull(templates);
            var text = new StringBuilder();
            text.Append("Move ").Append(Text.Count(templates.Count, "template folder")).Append(" to the Recycle Bin?").Append(Paragraph);
            text.AppendLine(Text.List(templates.Select(t => t.Name + "  (" + t.Folder + ")"), 20));
            text.AppendLine();
            text.Append("Their ROIs, monitored folders and DICOM requirements go with them; they can be restored from the Recycle Bin. "
                + "RTs they generated earlier are not deleted, and no new RTs are written for them. "
                + "Windows may ask again; if it cannot recycle a folder, it asks before deleting it permanently.");
            if (notRecyclable != null && notRecyclable.Count > 0)
            {
                text.Append(Paragraph).Append(DescribeNotRecyclable(notRecyclable));
            }

            if (hiddenSelected > 0)
            {
                text.Append(Paragraph).Append(HiddenNote(hiddenSelected));
            }

            return text.ToString();
        }

        /// <summary>The selected template folders that are not deleted because they have no Recycle Bin, and what to do instead.</summary>
        public static string DescribeNotRecyclable(IReadOnlyList<NotRecyclable> notRecyclable)
        {
            ArgumentNullException.ThrowIfNull(notRecyclable);
            return (notRecyclable.Count == 1 ? "This template folder is not deleted, because " : $"These {notRecyclable.Count} template folders are not deleted, because ")
                + "deleting there would be permanent (no Recycle Bin):" + Environment.NewLine
                + Text.List(notRecyclable.Select(n => n.Name + "  (" + n.Folder + "): " + n.Reason), 20) + Environment.NewLine
                + "To delete " + (notRecyclable.Count == 1 ? "it" : "them") + " anyway, use File Explorer, or copy "
                + (notRecyclable.Count == 1 ? "it" : "them") + " somewhere safe first.";
        }

